CREATE TABLE sellers (
  id                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name               VARCHAR2(200) NOT NULL,
  email              VARCHAR2(320) NOT NULL,
  password_hash      VARCHAR2(200),
  telegram_chat_id   NUMBER(19),
  telegram_link_code VARCHAR2(32),
  created_at         TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT sellers_email_uq UNIQUE (email),
  CONSTRAINT sellers_link_code_uq UNIQUE (telegram_link_code)
)
/
CREATE TABLE products (
  id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  seller_id     NUMBER NOT NULL,
  sku           VARCHAR2(64) NOT NULL,
  title         VARCHAR2(300) NOT NULL,
  cost_price    NUMBER(12,2) NOT NULL,
  current_price NUMBER(12,2) NOT NULL,
  created_at    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT products_seller_fk FOREIGN KEY (seller_id) REFERENCES sellers (id),
  CONSTRAINT products_sku_uq UNIQUE (seller_id, sku),
  CONSTRAINT products_cost_ck CHECK (cost_price >= 0),
  CONSTRAINT products_price_ck CHECK (current_price > 0)
)
/
CREATE TABLE listings (
  id                     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  product_id             NUMBER NOT NULL,
  kind                   VARCHAR2(10) NOT NULL,
  marketplace            VARCHAR2(30) NOT NULL,
  sku                    VARCHAR2(64) NOT NULL,
  title                  VARCHAR2(300),
  last_price             NUMBER(12,2),
  in_stock               NUMBER(1),
  last_observed_at       TIMESTAMP,
  check_interval_seconds NUMBER DEFAULT 60 NOT NULL,
  next_check_at          TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  active                 NUMBER(1) DEFAULT 1 NOT NULL,
  created_at             TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT listings_product_fk FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT listings_sku_uq UNIQUE (product_id, marketplace, sku),
  CONSTRAINT listings_kind_ck CHECK (kind IN ('OWN', 'COMPETITOR')),
  CONSTRAINT listings_in_stock_ck CHECK (in_stock IN (0, 1)),
  CONSTRAINT listings_active_ck CHECK (active IN (0, 1))
)
/
CREATE INDEX listings_due_ix ON listings (active, next_check_at)
/
CREATE TABLE pricing_rules (
  product_id         NUMBER PRIMARY KEY,
  min_margin_pct     NUMBER(5,2) NOT NULL,
  price_floor        NUMBER(12,2) NOT NULL,
  price_ceiling      NUMBER(12,2) NOT NULL,
  undercut_step      NUMBER(12,2) DEFAULT 1 NOT NULL,
  jump_threshold_pct NUMBER(5,2) DEFAULT 20 NOT NULL,
  CONSTRAINT pricing_rules_product_fk FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT pricing_rules_range_ck CHECK (price_floor <= price_ceiling),
  CONSTRAINT pricing_rules_margin_ck CHECK (min_margin_pct >= 0),
  CONSTRAINT pricing_rules_step_ck CHECK (undercut_step >= 0)
)
/
CREATE TABLE price_history (
  id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  listing_id    NUMBER NOT NULL,
  price         NUMBER(12,2) NOT NULL,
  in_stock      NUMBER(1) NOT NULL,
  prev_price    NUMBER(12,2),
  change_pct    NUMBER(8,2),
  is_large_jump NUMBER(1) DEFAULT 0 NOT NULL,
  observed_at   TIMESTAMP NOT NULL,
  created_at    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT price_history_listing_fk FOREIGN KEY (listing_id) REFERENCES listings (id),
  CONSTRAINT price_history_reading_uq UNIQUE (listing_id, observed_at),
  CONSTRAINT price_history_in_stock_ck CHECK (in_stock IN (0, 1)),
  CONSTRAINT price_history_jump_ck CHECK (is_large_jump IN (0, 1))
)
/
CREATE TABLE price_suggestions (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  product_id      NUMBER NOT NULL,
  suggested_price NUMBER(12,2) NOT NULL,
  current_price   NUMBER(12,2) NOT NULL,
  reason          VARCHAR2(500),
  status          VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
  created_at      TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  resolved_at     TIMESTAMP,
  CONSTRAINT price_suggestions_product_fk FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT price_suggestions_status_ck CHECK (status IN ('PENDING', 'APPLIED', 'DISMISSED'))
)
/
CREATE INDEX price_suggestions_status_ix ON price_suggestions (product_id, status)
/
CREATE TABLE alerts (
  id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  seller_id     NUMBER NOT NULL,
  product_id    NUMBER NOT NULL,
  listing_id    NUMBER,
  suggestion_id NUMBER,
  alert_type    VARCHAR2(40) NOT NULL,
  message       VARCHAR2(1000) NOT NULL,
  created_at    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  sent_at       TIMESTAMP,
  CONSTRAINT alerts_seller_fk FOREIGN KEY (seller_id) REFERENCES sellers (id),
  CONSTRAINT alerts_product_fk FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT alerts_listing_fk FOREIGN KEY (listing_id) REFERENCES listings (id),
  CONSTRAINT alerts_suggestion_fk FOREIGN KEY (suggestion_id) REFERENCES price_suggestions (id),
  CONSTRAINT alerts_type_ck CHECK (
    alert_type IN ('COMPETITOR_PRICE_DROP', 'COMPETITOR_OUT_OF_STOCK', 'LARGE_JUMP', 'NEW_SUGGESTION')
  )
)
/
CREATE INDEX alerts_seller_ix ON alerts (seller_id, created_at)
/
CREATE TABLE daily_stats (
  product_id           NUMBER NOT NULL,
  stat_date            DATE NOT NULL,
  own_price            NUMBER(12,2),
  avg_competitor_price NUMBER(12,2),
  min_competitor_price NUMBER(12,2),
  price_rank           NUMBER,
  cheapest_share_pct   NUMBER(5,2),
  CONSTRAINT daily_stats_pk PRIMARY KEY (product_id, stat_date),
  CONSTRAINT daily_stats_product_fk FOREIGN KEY (product_id) REFERENCES products (id)
)
/
